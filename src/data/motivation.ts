/** Deterministic pick so the "daily" content stays the same all day. */
export function dailyIndex(len: number, dateKey: string, salt = 0): number {
  let h = salt * 31;
  for (const c of dateKey) h = (h * 33 + c.charCodeAt(0)) >>> 0;
  return h % len;
}
